-- Planetary geography, data provenance, biospheres, and simulation persistence.
-- Large raster tiles should be stored in object storage; MySQL stores metadata and tile manifests.
CREATE TABLE IF NOT EXISTS planetary_profiles (
  planet_id VARCHAR(96) PRIMARY KEY,
  system_id VARCHAR(96) NULL,
  display_name VARCHAR(160) NOT NULL,
  planet_class VARCHAR(48) NOT NULL,
  class_subtype VARCHAR(96) NULL,
  world_seed BIGINT UNSIGNED NOT NULL,
  generator_version VARCHAR(64) NOT NULL,
  radius_km DOUBLE NULL,
  mass_earth DOUBLE NULL,
  surface_gravity_m_s2 DOUBLE NULL,
  mean_temperature_c DOUBLE NULL,
  atmosphere_json JSON NOT NULL,
  hydrology_json JSON NOT NULL,
  geology_json JSON NOT NULL,
  biology_json JSON NOT NULL,
  provenance ENUM('measured','derived_from_measured','procedural','user_authored','mixed') NOT NULL DEFAULT 'procedural',
  source_manifest_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_planet_system (system_id),
  INDEX idx_planet_class (planet_class)
);

CREATE TABLE IF NOT EXISTS planetary_map_layers (
  layer_id VARCHAR(128) PRIMARY KEY,
  planet_id VARCHAR(96) NOT NULL,
  layer_type VARCHAR(64) NOT NULL,
  layer_name VARCHAR(160) NOT NULL,
  source_id VARCHAR(128) NULL,
  source_product_id VARCHAR(255) NULL,
  source_version VARCHAR(96) NULL,
  source_url TEXT NULL,
  license_label VARCHAR(160) NULL,
  attribution_text TEXT NULL,
  coordinate_reference_system VARCHAR(96) NOT NULL DEFAULT 'planetographic_lon_lat',
  resolution_m DOUBLE NULL,
  units_label VARCHAR(64) NULL,
  epoch_label VARCHAR(96) NULL,
  min_zoom SMALLINT NOT NULL DEFAULT 0,
  max_zoom SMALLINT NOT NULL DEFAULT 18,
  visibility_default BOOLEAN NOT NULL DEFAULT TRUE,
  style_json JSON NOT NULL,
  tile_manifest_json JSON NOT NULL,
  provenance ENUM('measured','derived_from_measured','procedural','user_authored','mixed') NOT NULL DEFAULT 'procedural',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  INDEX idx_map_layer_planet (planet_id),
  INDEX idx_map_layer_type (layer_type),
  CONSTRAINT fk_map_layer_planet FOREIGN KEY (planet_id) REFERENCES planetary_profiles(planet_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS planetary_surface_tiles (
  tile_id VARCHAR(160) PRIMARY KEY,
  planet_id VARCHAR(96) NOT NULL,
  layer_id VARCHAR(128) NOT NULL,
  zoom_level SMALLINT NOT NULL,
  tile_x INT NOT NULL,
  tile_y INT NOT NULL,
  content_hash CHAR(64) NOT NULL,
  storage_uri TEXT NOT NULL,
  width_px SMALLINT NOT NULL,
  height_px SMALLINT NOT NULL,
  format_label VARCHAR(32) NOT NULL,
  generated_seed BIGINT UNSIGNED NULL,
  generator_version VARCHAR(64) NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_planet_tile (planet_id, layer_id, zoom_level, tile_x, tile_y),
  CONSTRAINT fk_surface_tile_planet FOREIGN KEY (planet_id) REFERENCES planetary_profiles(planet_id) ON DELETE CASCADE,
  CONSTRAINT fk_surface_tile_layer FOREIGN KEY (layer_id) REFERENCES planetary_map_layers(layer_id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS planetary_biosphere_entities (
  entity_id VARCHAR(128) PRIMARY KEY,
  planet_id VARCHAR(96) NOT NULL,
  parent_entity_id VARCHAR(128) NULL,
  entity_kind ENUM('domain','kingdom','phylum','class','order','family','genus','species','population','habitat') NOT NULL,
  scientific_name VARCHAR(180) NULL,
  common_name VARCHAR(180) NOT NULL,
  fictional BOOLEAN NOT NULL DEFAULT TRUE,
  traits_json JSON NOT NULL,
  population_estimate BIGINT UNSIGNED NULL,
  habitat_layer_id VARCHAR(128) NULL,
  simulation_state_json JSON NOT NULL,
  provenance ENUM('measured','procedural','user_authored') NOT NULL DEFAULT 'procedural',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_bio_planet (planet_id),
  INDEX idx_bio_parent (parent_entity_id),
  CONSTRAINT fk_bio_planet FOREIGN KEY (planet_id) REFERENCES planetary_profiles(planet_id) ON DELETE CASCADE,
  CONSTRAINT fk_bio_parent FOREIGN KEY (parent_entity_id) REFERENCES planetary_biosphere_entities(entity_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS map_settlement_features (
  feature_id VARCHAR(128) PRIMARY KEY,
  planet_id VARCHAR(96) NOT NULL,
  parent_feature_id VARCHAR(128) NULL,
  feature_type ENUM('continent','region','kingdom','province','capital','city','town','village','hamlet','castle','fortress','port','farm','mine','monastery','landmark') NOT NULL,
  display_name VARCHAR(180) NOT NULL,
  latitude DOUBLE NOT NULL,
  longitude DOUBLE NOT NULL,
  elevation_m DOUBLE NULL,
  population BIGINT UNSIGNED NOT NULL DEFAULT 0,
  owner_faction_id VARCHAR(128) NULL,
  world_seed BIGINT UNSIGNED NOT NULL,
  generated BOOLEAN NOT NULL DEFAULT TRUE,
  properties_json JSON NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_feature_planet_position (planet_id, latitude, longitude),
  INDEX idx_feature_parent (parent_feature_id),
  CONSTRAINT fk_feature_planet FOREIGN KEY (planet_id) REFERENCES planetary_profiles(planet_id) ON DELETE CASCADE,
  CONSTRAINT fk_feature_parent FOREIGN KEY (parent_feature_id) REFERENCES map_settlement_features(feature_id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS map_road_edges (
  road_id VARCHAR(160) PRIMARY KEY,
  planet_id VARCHAR(96) NOT NULL,
  from_feature_id VARCHAR(128) NOT NULL,
  to_feature_id VARCHAR(128) NOT NULL,
  road_class ENUM('imperial','royal','regional','local','trail','trade_route','sea_lane') NOT NULL,
  surface_type VARCHAR(64) NOT NULL DEFAULT 'packed_earth',
  distance_km DOUBLE NOT NULL,
  estimated_travel_hours DOUBLE NULL,
  seasonal BOOLEAN NOT NULL DEFAULT FALSE,
  toll_amount DOUBLE NOT NULL DEFAULT 0,
  geometry_json JSON NOT NULL,
  provenance ENUM('measured','historical_source','procedural','user_authored') NOT NULL DEFAULT 'procedural',
  properties_json JSON NOT NULL,
  INDEX idx_road_planet (planet_id),
  INDEX idx_road_from (from_feature_id),
  INDEX idx_road_to (to_feature_id),
  CONSTRAINT fk_road_planet FOREIGN KEY (planet_id) REFERENCES planetary_profiles(planet_id) ON DELETE CASCADE,
  CONSTRAINT fk_road_from FOREIGN KEY (from_feature_id) REFERENCES map_settlement_features(feature_id) ON DELETE CASCADE,
  CONSTRAINT fk_road_to FOREIGN KEY (to_feature_id) REFERENCES map_settlement_features(feature_id) ON DELETE CASCADE
);
